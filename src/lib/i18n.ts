const dicts: Record<Locale, Dict> = { ru, uk, en, de, fr }

export function t(key: string, locale?: string, vars?: Record<string, string | number>): string {
  const loc = locale || currentLocale
  const d = (dicts as Record<string, Dict>)[loc] ?? dicts.en
  let s = d[key] ?? dicts.en[key] ?? key
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v))
  return s
}

